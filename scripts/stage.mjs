#!/usr/bin/env node
/**
 * STAGE — copy content/<slug>/script.json into public/<slug>/ so the compositions can load it (with or without
 * timings), and regenerate src/registry.ts from every content/<slug>/script.json. Run after every script edit.
 *
 *   node scripts/stage.mjs <slug>        one video
 *   node scripts/stage.mjs --all         every video in content/ (npm run dev does this first)
 *
 * A script whose beats use `short` visuals becomes a vertical Short-<slug> composition; every other script
 * becomes Video-<slug> plus Thumb-<slug>.
 */
import { mkdirSync, copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const arg = process.argv[2];
if (!arg) { console.error('usage: node scripts/stage.mjs <slug> | --all'); process.exit(2); }

const all = readdirSync('content', { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(`content/${d.name}/script.json`))
  .map((d) => d.name)
  .sort();

const slugs = arg === '--all' ? all : [arg];
for (const slug of slugs) {
  if (!/^[a-z0-9-]+$/.test(slug)) { console.error(`invalid slug "${slug}" (lowercase letters, digits and dashes)`); process.exit(2); }
  const src = `content/${slug}/script.json`;
  if (!existsSync(src)) { console.error(`no ${src}`); process.exit(1); }
  mkdirSync(`public/${slug}`, { recursive: true });
  copyFileSync(src, `public/${slug}/script.json`);
  console.log(`staged public/${slug}/script.json`);
}

const isShort = (slug) => {
  const s = JSON.parse(readFileSync(`content/${slug}/script.json`, 'utf8'));
  return (s.beats ?? []).some((b) => b.visual?.type === 'short');
};
const videos = all.filter((s) => !isShort(s)), shorts = all.filter(isShort);
const list = (xs) => xs.map((s) => `  '${s}',`).join('\n');
const registry = `/** GENERATED by scripts/stage.mjs from content/<slug>/script.json — do not edit by hand. */
/** Long videos: compositions Video-<slug> (1920x1080) and Thumb-<slug> (1280x720). */
export const SLUGS: string[] = [
${list(videos)}
];
/** Vertical Shorts (beats with \`short\` visuals): compositions Short-<slug> (1080x1920). Render with scripts/render-short.mjs. */
export const SHORTS: string[] = [
${list(shorts)}
];
`;
const path = 'src/registry.ts';
if (!existsSync(path) || readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== registry) {   // a Windows checkout may have CRLF
  writeFileSync(path, registry);
  console.log(`src/registry.ts: ${videos.length} video(s), ${shorts.length} Short(s)`);
}
